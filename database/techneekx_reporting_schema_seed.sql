-- TechNeekX Community Reporting System
-- PostgreSQL schema + sample seed data based on the supplied ER diagram.
-- Run this file in a NEW/empty database first. It is designed to be rerunnable
-- for the sample rows (ON CONFLICT DO NOTHING), but does not delete existing data.

BEGIN;

CREATE TABLE IF NOT EXISTS roles (
    role_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL UNIQUE,
    description   TEXT
);

CREATE TABLE IF NOT EXISTS teams (
    team_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    type           VARCHAR(50) NOT NULL,
    parent_team_id INTEGER REFERENCES teams(team_id) ON DELETE SET NULL,
    description    TEXT
);

CREATE TABLE IF NOT EXISTS groups (
    group_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL,
    team_id      INTEGER NOT NULL REFERENCES teams(team_id) ON DELETE CASCADE,
    description  TEXT,
    UNIQUE (team_id, name)
);

CREATE TABLE IF NOT EXISTS users (
    user_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    email       VARCHAR(255) NOT NULL UNIQUE,
    password    TEXT NOT NULL, -- Store a Django password hash in real applications, never plaintext.
    role_id     INTEGER NOT NULL REFERENCES roles(role_id),
    team_id     INTEGER REFERENCES teams(team_id) ON DELETE SET NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'Active'
                CHECK (status IN ('Active', 'Inactive', 'Pending')),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS announcements (
    announcement_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           VARCHAR(200) NOT NULL,
    content         TEXT NOT NULL,
    created_by      INTEGER NOT NULL REFERENCES users(user_id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tasks (
    task_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(200) NOT NULL,
    description   TEXT NOT NULL,
    created_by    INTEGER NOT NULL REFERENCES users(user_id),
    assigned_to   INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    team_id       INTEGER REFERENCES teams(team_id) ON DELETE SET NULL,
    status        VARCHAR(30) NOT NULL DEFAULT 'Assigned'
                  CHECK (status IN ('Assigned', 'In Progress', 'Submitted',
                                    'Approved', 'Changes Requested')),
    deadline      TIMESTAMPTZ,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS task_proofs (
    proof_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       INTEGER NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
    submitted_by  INTEGER NOT NULL REFERENCES users(user_id),
    github_link   TEXT,
    screenshots   TEXT, -- URLs or JSON/text list of screenshot URLs
    description   TEXT,
    submitted_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (github_link IS NOT NULL OR screenshots IS NOT NULL OR description IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS reviews (
    review_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      INTEGER NOT NULL REFERENCES tasks(task_id) ON DELETE CASCADE,
    proof_id     INTEGER REFERENCES task_proofs(proof_id) ON DELETE SET NULL,
    reviewer_id  INTEGER NOT NULL REFERENCES users(user_id),
    decision     VARCHAR(30) NOT NULL
                 CHECK (decision IN ('Approved', 'Changes Requested')),
    feedback     TEXT,
    reviewed_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS performance (
    performance_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    points         INTEGER NOT NULL DEFAULT 0 CHECK (points >= 0),
    rank           INTEGER CHECK (rank IS NULL OR rank > 0),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS history_logs (
    log_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    action      VARCHAR(120) NOT NULL,
    details     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS extra_material (
    material_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    type        VARCHAR(60) NOT NULL,
    created_by  INTEGER NOT NULL REFERENCES users(user_id),
    file_url    TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Helpful indexes for common dashboard and queue queries.
CREATE INDEX IF NOT EXISTS idx_users_role_id ON users(role_id);
CREATE INDEX IF NOT EXISTS idx_users_team_id ON users(team_id);
CREATE INDEX IF NOT EXISTS idx_tasks_assigned_to_status ON tasks(assigned_to, status);
CREATE INDEX IF NOT EXISTS idx_tasks_team_status ON tasks(team_id, status);
CREATE INDEX IF NOT EXISTS idx_tasks_deadline ON tasks(deadline);
CREATE INDEX IF NOT EXISTS idx_proofs_task_submitted_at ON task_proofs(task_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_reviews_task_reviewed_at ON reviews(task_id, reviewed_at DESC);
CREATE INDEX IF NOT EXISTS idx_history_logs_created_at ON history_logs(created_at DESC);

